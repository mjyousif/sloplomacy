#!/usr/bin/env python3
"""Generate frontend TypeScript schemas, HTTP SDK, and WebSocket helpers from FastAPI OpenAPI.

Usage:
    python scripts/generate_api.py          # write frontend/src/api/schema.gen.ts and sdk.gen.ts
    python scripts/generate_api.py --check  # exit 0 if up to date, non-zero if drifted
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parent.parent
BACKEND_DIR = REPO_ROOT / "backend"
FRONTEND_API_DIR = REPO_ROOT / "frontend" / "src" / "api"
SCHEMA_PATH = FRONTEND_API_DIR / "schema.gen.ts"
SDK_PATH = FRONTEND_API_DIR / "sdk.gen.ts"

# Ensure imports inside backend/ (e.g. `from api import ...`) resolve regardless of cwd.
for _p in (str(BACKEND_DIR), str(REPO_ROOT)):
    if _p not in sys.path:
        sys.path.insert(0, _p)

from domain.game_state import PhaseTimer  # noqa: E402
from domain.requests import (  # noqa: E402
    WebSocketAuthMessage,
    WebSocketGameUpdate,
    WebSocketLobbyUpdate,
    WebSocketPingMessage,
    WebSocketPong,
    WebSocketRefreshMessage,
)
from fastapi.routing import APIWebSocketRoute  # noqa: E402
from main import app  # noqa: E402

HEADER = "// AUTO-GENERATED by scripts/generate_api.py — DO NOT EDIT MANUALLY."

WS_MODELS = (
    WebSocketAuthMessage,
    WebSocketGameUpdate,
    WebSocketLobbyUpdate,
    WebSocketPingMessage,
    WebSocketPong,
    WebSocketRefreshMessage,
)

# Narrow TypeScript types for backend dict[str, Any] / dict[Power, ...] fields.
FIELD_TYPE_OVERRIDES: dict[tuple[str, str], str] = {
    ("PhaseTimer", "votes"): "Partial<Record<Power, TimerChoice>>",
    ("SimulationResult", "builds"): "Record<Power, BuildSummary> | null",
    ("SimulationResult", "retreats"): "Record<Power, Record<string, string[]>> | null",
    ("GameState", "builds"): "Record<Power, BuildSummary> | null",
    ("GameState", "retreats"): "Record<Power, Record<string, string[]>> | null",
    ("TurnRecord", "builds"): "Record<Power, BuildSummary> | null",
    ("TurnRecord", "retreats"): "Record<Power, Record<string, string[]>> | null",
}

# Non-nullable defaulted fields that callers construct or consume as optional properties.
OPTIONAL_RESPONSE_FIELDS: dict[str, set[str]] = {
    "AdminStatusResponse": {"history_entries"},
    "GameParticipant": {"surrendered"},
    "GameState": {"surrendered_powers", "admin_log", "state_revision", "unit_options"},
    "MultiplayerGameSummary": {
        "surrendered_powers",
        "is_draft",
        "is_private",
        "has_passcode",
    },
    "Unit": {"is_dislodged"},
}


def snake_to_camel(name: str) -> str:
    parts = [p for p in name.split("_") if p]
    if not parts:
        return name
    return parts[0].lower() + "".join(p.capitalize() for p in parts[1:])


def snake_to_pascal(name: str) -> str:
    return "".join(p.capitalize() for p in name.split("_") if p)


def collect_schemas() -> dict[str, dict[str, Any]]:
    spec = app.openapi()
    schemas: dict[str, dict[str, Any]] = dict(spec.get("components", {}).get("schemas", {}))
    # Include @computed_field outputs (remaining_seconds, extensions_needed) on PhaseTimer.
    schemas["PhaseTimer"] = PhaseTimer.model_json_schema(
        mode="serialization",
        ref_template="#/components/schemas/{model}",
    )
    for model in WS_MODELS:
        model_schema = model.model_json_schema(ref_template="#/components/schemas/{model}")
        model_schema.pop("$defs", None)
        schemas[model.__name__] = model_schema
    return schemas


def _has_null(ts_type: str) -> bool:
    return "null" in [part.strip() for part in ts_type.split("|")]


def schema_to_ts(schema: dict[str, Any] | None) -> str:
    if not schema:
        return "unknown"
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "const" in schema:
        val = schema["const"]
        if isinstance(val, str):
            return f"'{val}'"
        if isinstance(val, bool):
            return "true" if val else "false"
        return repr(val)
    if "enum" in schema:
        return " | ".join(
            f"'{v}'" if isinstance(v, str) else ("null" if v is None else str(v))
            for v in schema["enum"]
        )
    if "anyOf" in schema:
        parts = [schema_to_ts(sub) for sub in schema["anyOf"]]
        deduped: list[str] = []
        for p in parts:
            if p not in deduped:
                deduped.append(p)
        return " | ".join(deduped)
    if "oneOf" in schema:
        parts = [schema_to_ts(sub) for sub in schema["oneOf"]]
        return " | ".join(dict.fromkeys(parts))
    if "allOf" in schema:
        parts = [schema_to_ts(sub) for sub in schema["allOf"]]
        return " & ".join(parts)

    t = schema.get("type")
    if t == "string":
        return "string"
    if t in ("integer", "number"):
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "null":
        return "null"
    if t == "array":
        items = schema_to_ts(schema.get("items"))
        if " | " in items or " & " in items:
            return f"({items})[]"
        return f"{items}[]"
    if t == "object":
        addl = schema.get("additionalProperties")
        if isinstance(addl, dict):
            return f"Record<string, {schema_to_ts(addl)}>"
        if addl is True:
            return "Record<string, unknown>"
        props = schema.get("properties", {})
        if props:
            req = set(schema.get("required", []))
            fields = [f"{k}{'' if k in req else '?'}: {schema_to_ts(v)}" for k, v in props.items()]
            return "{ " + "; ".join(fields) + " }"
        return "Record<string, unknown>"
    return "unknown"


def is_property_optional(
    schema_name: str,
    prop_name: str,
    prop_schema: dict[str, Any],
    ts_type: str,
    required_set: set[str],
) -> bool:
    if "const" in prop_schema:
        # Literal discriminators (e.g. WebSocket `type`) are always emitted on the wire.
        return False
    if schema_name.endswith("Request") or re.match(r"^WebSocket.*Message$", schema_name):
        return prop_name not in required_set
    if prop_name in OPTIONAL_RESPONSE_FIELDS.get(schema_name, set()):
        return True
    return prop_name not in required_set and _has_null(ts_type)


def format_type_alias(name: str, rhs: str) -> list[str]:
    one_line = f"export type {name} = {rhs};"
    if len(one_line) <= 80:
        return [one_line]
    parts = [p.strip() for p in rhs.split("|")]
    if len(parts) > 1:
        return [f"export type {name} =", *[f"  | {p}" for p in parts[:-1]], f"  | {parts[-1]};"]
    return [one_line]


def collect_refs_in_ts(ts_type: str, known_schemas: set[str]) -> set[str]:
    tokens = set(re.findall(r"\b[A-Za-z_][A-Za-z0-9_]*\b", ts_type))
    return tokens & known_schemas


def extract_operations() -> list[dict[str, Any]]:
    spec = app.openapi()
    ops: list[dict[str, Any]] = []
    for raw_path, path_item in sorted(spec.get("paths", {}).items()):
        for method, op in sorted(path_item.items()):
            if method.lower() not in {"get", "post", "put", "patch", "delete"}:
                continue
            op_id = op["operationId"]
            params = op.get("parameters", [])
            path_params = [
                {
                    "name": p["name"],
                    "ts": schema_to_ts(p.get("schema")),
                    "required": True,
                }
                for p in params
                if p.get("in") == "path"
            ]
            query_params = [
                {
                    "name": p["name"],
                    "ts": schema_to_ts(p.get("schema")),
                    "required": bool(p.get("required", False)),
                }
                for p in params
                if p.get("in") == "query"
            ]
            req_body = op.get("requestBody", {})
            body_schema = req_body.get("content", {}).get("application/json", {}).get("schema")
            body_ts = schema_to_ts(body_schema) if body_schema is not None else None
            body_required = bool(req_body.get("required", False))
            resp_schema = (
                op.get("responses", {})
                .get("200", {})
                .get("content", {})
                .get("application/json", {})
                .get("schema")
            )
            resp_ts = schema_to_ts(resp_schema) if resp_schema is not None else "unknown"
            ops.append(
                {
                    "path": raw_path,
                    "client_path": raw_path[4:] if raw_path.startswith("/api") else raw_path,
                    "method": method.upper(),
                    "operation_id": op_id,
                    "fn_name": snake_to_camel(op_id),
                    "pascal_name": snake_to_pascal(op_id),
                    "path_params": path_params,
                    "query_params": query_params,
                    "body_ts": body_ts,
                    "body_required": body_required,
                    "resp_ts": resp_ts,
                }
            )
    return ops


def extract_ws_routes() -> list[dict[str, Any]]:
    ws_routes: list[dict[str, Any]] = []
    for route in app.routes:
        if isinstance(route, APIWebSocketRoute):
            ws_routes.append(
                {
                    "path": route.path,
                    "name": route.name,
                    "fn_name": f"{snake_to_camel(route.name)}Path",
                    "pascal_name": snake_to_pascal(route.name),
                    "path_params": [p.name for p in route.dependant.path_params],
                    "query_params": [p.name for p in route.dependant.query_params],
                }
            )
    ws_routes.sort(key=lambda r: r["path"])
    return ws_routes


def _render_field_lines(fields: list[tuple[str, str, bool]]) -> list[str]:
    lines: list[str] = []
    for name, ts_type, optional in fields:
        sep = "?:" if optional else ":"
        single = f"  {name}{sep} {ts_type};"
        if len(single) <= 80 or " | " not in ts_type or "Record<" in ts_type or "{" in ts_type:
            lines.append(single)
        else:
            parts = [p.strip() for p in ts_type.split("|")]
            lines.append(f"  {name}{sep}")
            for part in parts[:-1]:
                lines.append(f"    | {part}")
            lines.append(f"    | {parts[-1]};")
    return lines


def render_schema_ts() -> str:
    schemas = collect_schemas()
    ops = extract_operations()
    lines: list[str] = [HEADER, ""]

    enum_names = sorted(name for name, s in schemas.items() if "enum" in s)
    obj_names = sorted(name for name, s in schemas.items() if "enum" not in s)

    for name in enum_names:
        rhs = schema_to_ts(schemas[name])
        lines.extend(format_type_alias(name, rhs))
        lines.append("")

    lines.extend(
        [
            "export interface BuildSummary {",
            "  count: number;",
            "  homes: string[];",
            "}",
            "",
        ]
    )

    for name in obj_names:
        schema = schemas[name]
        props = schema.get("properties", {})
        required_set = set(schema.get("required", []))
        lines.append(f"export interface {name} {{")
        rendered_fields: list[tuple[str, str, bool]] = []
        for prop_name, prop_schema in props.items():
            ts_type = FIELD_TYPE_OVERRIDES.get((name, prop_name)) or schema_to_ts(prop_schema)
            optional = is_property_optional(name, prop_name, prop_schema, ts_type, required_set)
            rendered_fields.append((prop_name, ts_type, optional))
        lines.extend(_render_field_lines(rendered_fields))
        lines.append("}")
        lines.append("")

    lines.extend(
        [
            "export type WebSocketServerMessage =",
            "  | WebSocketGameUpdate",
            "  | WebSocketLobbyUpdate",
            "  | WebSocketPong;",
            "",
            "export type WebSocketMessage = WebSocketServerMessage;",
            "",
            "export type WebSocketClientMessage =",
            "  | WebSocketAuthMessage",
            "  | WebSocketPingMessage",
            "  | WebSocketRefreshMessage;",
            "",
        ]
    )

    # Operations and Paths maps generated from FastAPI routes
    lines.append("export interface operations {")
    for op in ops:
        lines.append(f"  {op['operation_id']}: {{")
        if op["path_params"] or op["query_params"]:
            lines.append("    parameters: {")
            if op["path_params"]:
                lines.append("      path: {")
                for p in op["path_params"]:
                    lines.append(f"        {p['name']}: {p['ts']};")
                lines.append("      };")
            if op["query_params"]:
                lines.append("      query?: {")
                for q in op["query_params"]:
                    lines.append(f"        {q['name']}{'' if q['required'] else '?'}: {q['ts']};")
                lines.append("      };")
            lines.append("    };")
        if op["body_ts"] is not None:
            opt_mark = "" if op["body_required"] else "?"
            lines.append(f"    requestBody{opt_mark}: {{")
            lines.append(f"      'application/json': {op['body_ts']};")
            lines.append("    };")
        lines.append("    responses: {")
        lines.append("      200: {")
        lines.append(f"        'application/json': {op['resp_ts']};")
        lines.append("      };")
        lines.append("    };")
        lines.append("  };")
    lines.append("}")
    lines.append("")

    by_path: dict[str, list[dict[str, Any]]] = {}
    for op in ops:
        by_path.setdefault(op["path"], []).append(op)
    lines.append("export interface paths {")
    for raw_path, path_ops in by_path.items():
        lines.append(f"  '{raw_path}': {{")
        for op in path_ops:
            lines.append(f"    {op['method'].lower()}: operations['{op['operation_id']}'];")
        lines.append("  };")
    lines.append("}")
    lines.append("")

    return "\n".join(lines)


def _format_fn_sig(prefix: str, params: list[str], ret_type: str) -> list[str]:
    one_line = f"{prefix}({', '.join(params)}): {ret_type} {{"
    if len(one_line) <= 80:
        return [one_line]
    return [
        f"{prefix}(",
        *[f"  {p}," for p in params],
        f"): {ret_type} {{",
    ]


def _format_client_path_expr(client_path: str) -> str:
    if "{" not in client_path:
        return f"'{client_path}'"
    replaced = re.sub(
        r"\{([A-Za-z0-9_]+)\}",
        lambda m: f"${{encodeURIComponent(String(path.{m.group(1)}))}}",
        client_path,
    )
    return f"`{replaced}`"


def render_sdk_ts() -> str:
    schemas = collect_schemas()
    known_types = set(schemas.keys()) | {"BuildSummary"}
    ops = extract_operations()
    ws_routes = extract_ws_routes()

    referenced_types: set[str] = set()
    for op in ops:
        for p in op["path_params"]:
            referenced_types |= collect_refs_in_ts(p["ts"], known_types)
        for q in op["query_params"]:
            referenced_types |= collect_refs_in_ts(q["ts"], known_types)
        if op["body_ts"]:
            referenced_types |= collect_refs_in_ts(op["body_ts"], known_types)
        referenced_types |= collect_refs_in_ts(op["resp_ts"], known_types)

    lines: list[str] = [
        HEADER,
        "import { apiFetch, apiJson, type ClientRequestInit } from './client';",
    ]
    if referenced_types:
        sorted_refs = sorted(referenced_types, key=str.casefold)
        single_import = f"import type {{ {', '.join(sorted_refs)} }} from './schema.gen';"
        if len(single_import) <= 80:
            lines.append(single_import)
        else:
            lines.append("import type {")
            for item in sorted_refs:
                lines.append(f"  {item},")
            lines.append("} from './schema.gen';")
    lines.append("")

    for op in ops:
        has_path = bool(op["path_params"])
        has_query = bool(op["query_params"])
        has_body = op["body_ts"] is not None
        needs_custom_options = has_path or has_query or has_body
        pascal = op["pascal_name"]
        opts_name = f"{pascal}Options" if needs_custom_options else "ClientRequestInit"

        if has_path:
            lines.append(f"export interface {pascal}Path {{")
            for p in op["path_params"]:
                lines.append(f"  {p['name']}: {p['ts']};")
            lines.append("}")
            lines.append("")

        if has_query:
            # Type alias (rather than interface) gives an implicit index signature for QueryParams.
            lines.append(f"export type {pascal}Query = {{")
            for q in op["query_params"]:
                lines.append(f"  {q['name']}{'' if q['required'] else '?'}: {q['ts']};")
            lines.append("};")
            lines.append("")

        if needs_custom_options:
            omit_keys: list[str] = []
            if has_body:
                omit_keys.append("'body'")
            if has_query:
                omit_keys.append("'query'")
            if omit_keys:
                omit_union = " | ".join(omit_keys)
                single_opt_line = (
                    f"export type {opts_name} = Omit<ClientRequestInit, {omit_union}> & {{"
                )
                if len(single_opt_line) <= 80:
                    lines.append(single_opt_line)
                else:
                    lines.extend(
                        [
                            f"export type {opts_name} = Omit<",
                            "  ClientRequestInit,",
                            f"  {omit_union}",
                            "> & {",
                        ]
                    )
            else:
                lines.append(f"export type {opts_name} = ClientRequestInit & {{")
            if has_path:
                lines.append(f"  path: {pascal}Path;")
            if has_query:
                lines.append(f"  query?: {pascal}Query;")
            if has_body:
                opt_mark = "" if op["body_required"] else "?"
                lines.append(f"  body{opt_mark}: {op['body_ts']};")
            lines.append("};")
            lines.append("")

        is_opts_required = has_path or (has_body and op["body_required"])
        param_sig = f"options: {opts_name}" if is_opts_required else f"options: {opts_name} = {{}}"
        path_expr = _format_client_path_expr(op["client_path"])

        destructured: list[str] = []
        if has_path:
            destructured.append("path")
        if has_query:
            destructured.append("query")
        if has_body:
            destructured.append("body")

        lines.extend(
            _format_fn_sig(
                f"export function {op['fn_name']}",
                [param_sig],
                "Promise<Response>",
            )
        )
        if destructured:
            lines.append(f"  const {{ {', '.join(destructured)}, ...rest }} = options;")
            rest_expr = "...rest"
        else:
            rest_expr = "...options"

        call_args = [rest_expr, f"method: '{op['method']}'"]
        if has_query:
            call_args.append("query")
        if has_body:
            call_args.append("body")

        call_line = f"  return apiFetch({path_expr}, {{ {', '.join(call_args)} }});"
        hug_line = f"  return apiFetch({path_expr}, {{"
        if len(call_line) <= 80:
            lines.append(call_line)
        elif len(hug_line) <= 80:
            lines.extend(
                [
                    hug_line,
                    *[f"    {arg}," for arg in call_args],
                    "  });",
                ]
            )
        else:
            lines.extend(
                [
                    "  return apiFetch(",
                    f"    {path_expr},",
                    "    {",
                    *[f"      {arg}," for arg in call_args],
                    "    },",
                    "  );",
                ]
            )
        lines.append("}")
        lines.append("")

        json_fn = f"{op['fn_name']}Json"
        lines.extend(
            _format_fn_sig(
                f"export function {json_fn}",
                [param_sig, "fallbackError?: string"],
                f"Promise<{op['resp_ts']}>",
            )
        )
        if destructured:
            lines.append(f"  const {{ {', '.join(destructured)}, ...rest }} = options;")
        single_args = f"{{ {', '.join(call_args)} }}"
        json_single_line = (
            f"  return apiJson<{op['resp_ts']}>({path_expr}, {single_args}, fallbackError);"
        )
        if len(json_single_line) <= 80:
            lines.append(json_single_line)
        else:
            args_line = f"    {single_args},"
            lines.append(f"  return apiJson<{op['resp_ts']}>(")
            lines.append(f"    {path_expr},")
            if len(args_line) <= 80:
                lines.append(args_line)
            else:
                lines.extend(["    {", *[f"      {arg}," for arg in call_args], "    },"])
            lines.extend(["    fallbackError,", "  );"])
        lines.append("}")
        lines.append("")

    # Typed WebSocket endpoint path builders generated from APIWebSocketRoute definitions
    for ws in ws_routes:
        if ws["path"] == "/ws/games/{game_id}":
            lines.extend(
                [
                    "export interface WsGameEndpointPath {",
                    "  game_id: string;",
                    "}",
                    "",
                    "export interface WsGameEndpointQuery {",
                    "  power?: string | null;",
                    "  passcode?: string | null;",
                    "  handshake?: boolean | '1' | '0' | number | null;",
                    "}",
                    "",
                    "export function wsGameEndpointPath(",
                    "  path: WsGameEndpointPath,",
                    "  query?: WsGameEndpointQuery,",
                    "): string {",
                    "  const base = `/ws/games/${encodeURIComponent(path.game_id)}`;",
                    "  if (!query) return base;",
                    "  const params = new URLSearchParams();",
                    "  if (query.handshake !== undefined && query.handshake !== null) {",
                    "    const hs =",
                    "      query.handshake === true ||",
                    "      query.handshake === '1' ||",
                    "      query.handshake === 1",
                    "        ? '1'",
                    "        : String(query.handshake);",
                    "    params.set('handshake', hs);",
                    "  }",
                    "  if (query.power !== undefined && query.power !== null && query.power !== '') {",
                    "    params.set('power', query.power);",
                    "  }",
                    "  if (",
                    "    query.passcode !== undefined &&",
                    "    query.passcode !== null &&",
                    "    query.passcode !== ''",
                    "  ) {",
                    "    params.set('passcode', query.passcode);",
                    "  }",
                    "  const qs = params.toString();",
                    "  return qs ? `${base}?${qs}` : base;",
                    "}",
                    "",
                ]
            )
        elif ws["path"] == "/ws/lobby":
            lines.extend(
                [
                    f"export function {ws['fn_name']}(): string {{",
                    "  return '/ws/lobby';",
                    "}",
                    "",
                ]
            )
        else:
            raise ValueError(f"Unhandled WebSocket route in generate_api.py: {ws['path']}")

    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Generate or check frontend API schema and SDK from FastAPI OpenAPI."
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Verify generated files match current backend OpenAPI spec without writing.",
    )
    args = parser.parse_args()

    expected_files = {
        SCHEMA_PATH: render_schema_ts(),
        SDK_PATH: render_sdk_ts(),
    }

    if args.check:
        drifted: list[Path] = []
        for path, expected in expected_files.items():
            actual = path.read_text(encoding="utf-8") if path.exists() else ""
            if actual != expected:
                drifted.append(path)
        if drifted:
            rel_list = ", ".join(str(p.relative_to(REPO_ROOT)) for p in drifted)
            print(
                f"API codegen out of date ({rel_list}). Run `python scripts/generate_api.py`.",
                file=sys.stderr,
            )
            return 1
        print("API codegen up to date.")
        return 0

    FRONTEND_API_DIR.mkdir(parents=True, exist_ok=True)
    for path, content in expected_files.items():
        path.write_bytes(content.encode("utf-8"))
        print(f"Wrote {path.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
